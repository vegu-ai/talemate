"""
Node glossary generator.

Renders a markdown reference page set covering every registered node type
(Python node classes and dynamically imported JSON module graphs) into
``docs/user-guide/node-editor/reference/nodes/``.

Each page covers one category of nodes (see ``PREFIX_MAP`` /
``MODULE_MAP``). Everything above the ``GENERATED_MARKER`` line in a page
is hand-written and preserved across regenerations; everything below it is
owned by this generator and rewritten on every ``--write`` run.

Node metadata is read the same way ``writer.py`` reads it: by
instantiating each registered class once. ``PropertyField`` attributes are
accessed directly instead of via ``model_dump()`` so user-supplied
``generate_choices`` callables (which may touch runtime-only state) are
never invoked.
"""

