# The generation types an image of each type is marked for. A generation
# of type X picks its references among the images marked for X (with
# character likeness first, then environment, then style), so an image is
# marked only for the generations that can use what it shows.
REFERENCE_TARGETS: dict[VIS_TYPE, list[VIS_TYPE]] = {
    VIS_TYPE.CHARACTER_PORTRAIT: [
        VIS_TYPE.CHARACTER_PORTRAIT,
        VIS_TYPE.CHARACTER_CARD,
        VIS_TYPE.SCENE_CARD,
        VIS_TYPE.SCENE_ILLUSTRATION,
    ],
    VIS_TYPE.CHARACTER_CARD: [
        VIS_TYPE.CHARACTER_PORTRAIT,
        VIS_TYPE.CHARACTER_CARD,
        VIS_TYPE.SCENE_CARD,
        VIS_TYPE.SCENE_ILLUSTRATION,
    ],
    VIS_TYPE.SCENE_BACKGROUND: [
        VIS_TYPE.SCENE_BACKGROUND,
        VIS_TYPE.SCENE_ILLUSTRATION,
        VIS_TYPE.CHARACTER_CARD,
    ],
    VIS_TYPE.SCENE_ILLUSTRATION: [VIS_TYPE.SCENE_ILLUSTRATION, VIS_TYPE.SCENE_CARD],
    VIS_TYPE.SCENE_CARD: [VIS_TYPE.SCENE_CARD, VIS_TYPE.SCENE_ILLUSTRATION],
    VIS_TYPE.OBJECT_ILLUSTRATION: [
        VIS_TYPE.OBJECT_ILLUSTRATION,
        VIS_TYPE.SCENE_ILLUSTRATION,
    ],
    VIS_TYPE.UNSPECIFIED: [],
}

ReferenceStep = Literal["analysis", "tags", "reference"]


class ReferenceStepError(pydantic.BaseModel):
    step: ReferenceStep
    message: str

    @classmethod
    def from_exception(cls, step: ReferenceStep, exc: BaseException):
        # an API error's text is the whole provider response; its body
        # holds the readable message
        body = getattr(exc, "body", None)
        message = body.get("message") if isinstance(body, dict) else None
        return cls(step=step, message=str(message or exc))


class ReferenceProgress(pydantic.BaseModel):
    asset_id: str
    # the step running now; None before the first one and once finished
    step: ReferenceStep | None = None
    finished: bool = False
    analyzed: bool = False
    tagged: bool = False
    marked: bool = False
    errors: list[ReferenceStepError] = pydantic.Field(default_factory=list)


class _CapturedReplies(Plugin):
    """
    Runs a websocket handler module without a websocket: the replies it
    would send to the frontend are kept for the caller.
    """

    router = "visual"

    def __init__(self, scene: "Scene"):
        self.replies: list[dict] = []
        super().__init__(SimpleNamespace(scene=scene, queue_put=self.replies.append))


class ReferenceMixin:
    async def generate_asset_tags(self, asset_id: str, text: str) -> list[str]:
        """
        Tags for an asset from a text describing it, generated by the
        Visual Library's "Sync from analysis" handler.
        """
        scene: "Scene" = self.scene
        router = _CapturedReplies(scene)
        handler = get_node("agents/visual/wshGenerateVisualAssetTags")()
        await FunctionWrapper(handler, handler, scene.nodegraph_state)(
            websocket_router=router,
            data={"asset_id": asset_id, "text": text},
        )
        reply = next(
            (r for r in router.replies if r.get("action") == "asset_tags_updated"),
            None,
        )
        if reply is None:
            raise ValueError("Tag generation returned no tags")
        return [tag for tag in reply.get("tags") or [] if tag]

    @set_processing
    async def mark_as_reference(
        self,
        asset_id: str,
        on_progress: Callable[[ReferenceProgress], Awaitable[None]] | None = None,
    ) -> ReferenceProgress:
        """
        Prepares an asset as a reference candidate: analyses it when a vision
        backend is available and it has no analysis yet, tags it from its
        analysis, and marks it for the REFERENCE_TARGETS of its type. A
        failed step is recorded and the next one still runs. Once the scene
        is released the chain stops and writes nothing more.
        """
        scene: "Scene" = self.scene
        assets = scene.assets
        progress = ReferenceProgress(asset_id=asset_id)

        async def enter(step: ReferenceStep | None):
            progress.step = step
            if on_progress:
                await on_progress(progress.model_copy(deep=True))

        def failed(step: ReferenceStep, exc: Exception):
            log.error("mark_as_reference.step_failed", step=step, error=str(exc))
            progress.errors.append(ReferenceStepError.from_exception(step, exc))

        async def released(step: ReferenceStep) -> bool:
            if scene.active:
                return False
            progress.errors.append(ReferenceStepError(step=step, message="Cancelled"))
            progress.finished = True
            await enter(None)
            return True

        def current_asset():
            if not assets.validate_asset_id(asset_id):
                raise ValueError("The image is no longer in the Visual Library")
            return assets.get_asset(asset_id)

        async def analyze(generate_tags: bool):
            return await self.analyze(
                AnalysisRequest(
                    prompt=DEFAULT_ANALYSIS_PROMPT,
                    asset_id=asset_id,
                    generate_tags=generate_tags,
                ),
                await_completion=True,
            )

        asset = current_asset()
        targets = REFERENCE_TARGETS[asset.meta.vis_type]
        if not targets:
            progress.errors.append(
                ReferenceStepError(
                    step="reference",
                    message="Give the image a type in the Visual Library first",
                )
            )
            progress.finished = True
            await enter(None)
            return progress

        if self.can_analyze_images and not asset.meta.analysis:
            await enter("analysis")
            try:
                try:
                    response = await analyze(generate_tags=True)
                except ExtractionError as exc:
                    if await released("analysis"):
                        return progress
                    log.warning("mark_as_reference.analysis_retry", error=str(exc))
                    response = await analyze(generate_tags=False)
                if not response.analysis:
                    raise ValueError("The analysis came back empty")
                if await released("analysis"):
                    return progress
                asset = current_asset()
                asset.meta.analysis = response.analysis
                asset.meta.add_tags(response.tags)
                assets.update_asset_meta(asset_id, asset.meta)
                progress.analyzed = True
                progress.tagged = bool(response.tags)
            except ControlFlowException:
                raise
            except Exception as exc:
                failed("analysis", exc)

        asset = current_asset()

        if asset.meta.analysis and not progress.tagged:
            if await released("tags"):
                return progress
            await enter("tags")
            try:
                tags = await self.generate_asset_tags(asset_id, asset.meta.analysis)
                if not tags:
                    raise ValueError("Tag generation returned no tags")
                if await released("tags"):
                    return progress
                asset = current_asset()
                asset.meta.add_tags(tags)
                assets.update_asset_meta(asset_id, asset.meta)
                progress.tagged = True
            except ControlFlowException:
                raise
            except Exception as exc:
                failed("tags", exc)

        if await released("reference"):
            return progress
        await enter("reference")
        try:
            asset = current_asset()
            asset.meta.add_reference(targets)
            assets.update_asset_meta(asset_id, asset.meta)
            progress.marked = True
        except Exception as exc:
            failed("reference", exc)

        scene.emit_status()
        progress.finished = True
        await enter(None)
        return progress
