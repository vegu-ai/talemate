"""
Integrity checks over the node modules that ship with the agents.

These files are edited as JSON rather than through the node editor often
enough that a hand edit can leave an edge behind. Neither half of a broken
socket reference is loud at runtime: a missing node raises a bare `KeyError`
out of `Graph.ensure_connections`, and a misspelled socket name only logs
`Input socket not found` and drops the connection, so the consuming node runs
on an unset value.

The socket names come from the generated node glossary under
`docs/user-guide/node-editor/reference/nodes/`, which carries every registry
path with its inputs and outputs. Reading them from the registry instead would
mean importing the whole node package, which no test process does.
"""

from __future__ import annotations

import glob
import json
import os
import re

import pytest

from talemate.path import TALEMATE_ROOT

MODULES = sorted(glob.glob(str(TALEMATE_ROOT / "src/talemate/agents/*/modules/*.json")))

INSTRUCT_MODULES = sorted(
    glob.glob(str(TALEMATE_ROOT / "src/talemate/agents/*/modules/instruct-*.json"))
)

GLOSSARY_DIR = TALEMATE_ROOT / "docs/user-guide/node-editor/reference/nodes"


def _parse_socket_table(section: str, heading: str) -> set[str] | None:
    """Socket names under `heading`, or None when the node declares no table."""
    if heading not in section:
        return None
    table = section.split(heading, 1)[1].split("\n**", 1)[0]
    return {
        match.group(1) for match in re.finditer(r"^\|\s*`([^`]+)`\s*\|", table, re.M)
    }


def _parse_glossary() -> dict[str, tuple[set[str] | None, set[str] | None]]:
    sockets = {}
    for path in glob.glob(str(GLOSSARY_DIR / "*.md")):
        for section in open(path).read().split("\n## ")[1:]:
            registry = re.search(r"^\s*`([^`]+)`\s*$", section, re.M)
            if not registry:
                continue
            inputs = _parse_socket_table(section, "**Inputs**")
            outputs = _parse_socket_table(section, "**Outputs**")
            if "dynamic inputs" in section:
                inputs = None
            sockets[registry.group(1)] = (inputs, outputs)
    return sockets


GLOSSARY = _parse_glossary()


def _read(path: str) -> dict:
    with open(path) as file:
        return json.load(file)


def _socket_refs(module: dict):
    """Every (node id, socket name, side) that an edge in this module names."""
    for source, destinations in (module.get("edges") or {}).items():
        node_id, socket = source.split(".", 1)
        yield node_id, socket, "outputs"
        for destination in destinations:
            node_id, socket = destination.split(".", 1)
            yield node_id, socket, "inputs"


def _nodes_of(module: dict, registry: str) -> list[dict]:
    return [
        node
        for node in (module.get("nodes") or {}).values()
        if node["registry"] == registry
    ]


def _callbacks_fed_by(
    module: dict, registry: str, *, name: str | None = None
) -> list[dict]:
    """Callbacks fed by `registry`; `name` matches that node, not the Callback."""
    nodes = module.get("nodes") or {}
    sources = {
        node_id
        for node_id, node in nodes.items()
        if node["registry"] == registry
        and (name is None or node["properties"].get("name") == name)
    }
    callbacks = []
    for source, destinations in (module.get("edges") or {}).items():
        node_id, socket = source.split(".", 1)
        if node_id not in sources or socket != "fn":
            continue
        for destination in destinations:
            target_id, target_socket = destination.split(".", 1)
            target = nodes.get(target_id)
            if (
                target
                and target["registry"] == "focal/Callback"
                and target_socket == "fn"
            ):
                callbacks.append(target)
    return callbacks


MULTI_FUNCTION_INSTRUCT_MODULES = [
    path
    for path in INSTRUCT_MODULES
    if _nodes_of(_read(path), "focal/Focal")
    and len(_nodes_of(_read(path), "focal/Callback")) >= 2
]
MULTI_CALL_MODULES = [
    path
    for path in MODULES
    if any(
        node["properties"].get("max_calls", 1) > 1
        for node in _nodes_of(_read(path), "focal/Focal")
    )
]
DIRECT_CONTEXT_UPDATE_MODULES = [
    path
    for path in MODULES
    if _callbacks_fed_by(_read(path), "agents/director/chat/directContextUpdate")
]


def test_shipped_modules_are_found():
    assert MODULES


def test_the_glossary_documents_every_registry_path_the_modules_use():
    undocumented = set()

    for path in MODULES:
        for node in (_read(path).get("nodes") or {}).values():
            if node["registry"] not in GLOSSARY:
                undocumented.add(node["registry"])

    assert not undocumented


@pytest.mark.parametrize("path", MODULES, ids=lambda p: os.path.basename(p))
def test_every_edge_refers_to_a_node_in_the_module(path):
    module = _read(path)
    node_ids = set(module.get("nodes") or {})

    dangling = {
        f"{node_id}.{socket}"
        for node_id, socket, _ in _socket_refs(module)
        if node_id not in node_ids
    }

    assert not dangling


@pytest.mark.parametrize("path", MODULES, ids=lambda p: os.path.basename(p))
def test_every_edge_names_a_socket_the_node_declares(path):
    module = _read(path)
    nodes = module.get("nodes") or {}

    unknown = set()
    for node_id, socket, side in _socket_refs(module):
        node = nodes.get(node_id)
        if not node:
            continue
        inputs, outputs = GLOSSARY.get(node["registry"], (None, None))
        declared = inputs if side == "inputs" else outputs
        if declared is not None and socket not in declared:
            unknown.add(f"{node['registry']}.{socket} ({side})")

    assert not unknown


def test_instruct_modules_are_found():
    assert INSTRUCT_MODULES


def test_multi_function_instruct_modules_are_found():
    assert MULTI_FUNCTION_INSTRUCT_MODULES


@pytest.mark.parametrize(
    "path", MULTI_FUNCTION_INSTRUCT_MODULES, ids=lambda p: os.path.basename(p)
)
def test_an_instruct_module_offering_several_functions_allows_several_calls(path):
    """One instruction routinely touches more than one field.

    The instruct modules execute an instruction the director routed to them, and
    the focal prompt renders `max_calls` as a hard ceiling. A module that offers
    several functions but allows a single call fails any instruction that needs
    two of them, and the model correctly reports the constraint instead of doing
    the work (issue #463).
    """
    module = _read(path)
    for node in _nodes_of(module, "focal/Focal"):
        assert node["properties"].get("max_calls", 1) > 1


def test_multi_call_modules_are_found():
    assert MULTI_CALL_MODULES


@pytest.mark.parametrize("path", MULTI_CALL_MODULES, ids=lambda p: os.path.basename(p))
def test_a_multi_call_module_offers_a_repeatable_callback(path):
    module = _read(path)
    callbacks = _nodes_of(module, "focal/Callback")
    assert any(
        callback["properties"].get("allow_multiple_calls") for callback in callbacks
    )


def test_direct_context_update_modules_are_found():
    assert DIRECT_CONTEXT_UPDATE_MODULES


@pytest.mark.parametrize(
    "path", DIRECT_CONTEXT_UPDATE_MODULES, ids=lambda p: os.path.basename(p)
)
def test_direct_context_update_may_be_called_more_than_once(path):
    """One call writes one Context ID.

    An instruction that names two of them - the default perspective and the NPC
    perspective, say - needs the function twice, so a callback exposing it must
    allow a repeat (issue #463).
    """
    callbacks = _callbacks_fed_by(
        _read(path), "agents/director/chat/directContextUpdate"
    )
    for callback in callbacks:
        assert callback["properties"].get("allow_multiple_calls")


def test_character_update_single_item_functions_allow_repeated_calls():
    """Each callback mutates one character item per call (issue #479)."""
    expected_functions = {
        "add_attribute",
        "remove_attribute",
        "add_detail",
        "remove_detail",
        "update_character_context",
    }
    module = _read(
        str(
            TALEMATE_ROOT
            / "src/talemate/agents/director/modules/instruct-character-updates.json"
        )
    )
    callbacks = _nodes_of(module, "focal/Callback")
    callback_functions = {
        node["properties"].get("name")
        for node in _nodes_of(module, "core/functions/GetFunction")
        if _callbacks_fed_by(
            module,
            "core/functions/GetFunction",
            name=node["properties"].get("name"),
        )
    }

    assert callback_functions == expected_functions
    assert len(callbacks) == len(expected_functions)

    for function_name in expected_functions:
        function_callbacks = _callbacks_fed_by(
            module, "core/functions/GetFunction", name=function_name
        )
        assert len(function_callbacks) == 1
        assert function_callbacks[0]["properties"].get("allow_multiple_calls")
