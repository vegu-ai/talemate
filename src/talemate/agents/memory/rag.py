def _entity_aliases(scene, name: str) -> set[str]:
    """The character's name and its name-mapping group, capitalisation kept."""
    aliases = {name}
    for key, values in scene.world_state.character_name_mappings.items():
        group = {key, *values}
        if name.lower() in {g.lower() for g in group}:
            aliases |= group
    return {a.strip() for a in aliases if a and a.strip()}


def _paragraph_order(doc_id: str) -> tuple[int, int]:
    tail = doc_id.rsplit(".", 1)[-1]
    return (1, int(tail)) if tail.isdigit() else (0, 0)


def _alias_named(alias: str, text: str) -> bool:
    """
    Whole-word match. An alias that carries a capital (a name) must appear
    with that capitalisation, so "Will" is not found in "I will go"; an alias
    that is lower-case in the name mappings matches case-insensitively.
    """
    if not alias:
        return False
    pattern = rf"\b{re.escape(alias)}\b"
    if alias == alias.lower():
        return re.search(pattern, text, re.IGNORECASE) is not None
    return re.search(pattern, text) is not None


log = structlog.get_logger()

ai_assisted_condition = AgentActionConditional(
    attribute="use_long_term_memory.config.retrieval_method",
    value=["queries", "questions"],
)


class MemoryRAGMixin:
    @classmethod
    def add_actions(cls, actions: dict[str, AgentAction]):
        actions["use_long_term_memory"] = AgentAction(
            enabled=True,
            container=True,
            can_be_disabled=True,
            icon="mdi-brain",
            label="Long Term Memory",
            description="Will augment the context with long term memory based on similarity queries. Semantic similarity will ALWAYS be used, but you can configure an AI assisted method to use on top of it.",
            config={
                "retrieval_method": AgentActionConfig(
                    type="text",
                    label="AI Assistance",
                    description="AI assisted context retrieval method.",
                    value="direct",
                    choices=[
                        {
                            "label": "None (Semantic similarity only)",
                            "value": "direct",
                        },
                        {
                            "label": "Context queries generated by AI",
                            "value": "queries",
                        },
                        {
                            "label": "AI compiled question and answers (slow)",
                            "value": "questions",
                        },
                    ],
                    note_on_value={
                        "queries": AgentActionNote(
                            color="primary",
                            text="Will send one additional request to the AI to compile a set of similarity queries to run against the long term memory (+1 request). Handled by the World State agent and uses the LLM client assigned to it.",
                        ),
                        "questions": AgentActionNote(
                            color="primary",
                            text="Will first prompt the LLM to compile a set of questions and then answer them (+2 requests). Handled by the World State agent and uses the LLM client assigned to it.",
                        ),
                    },
                ),
                "num_messages": AgentActionConfig(
                    type="number",
                    label="Number of Messages",
                    description="When retrieving context based on semantic similarity, this is the number of messages to consider (going back from the most recent message)",
                    value=3,
                    min=1,
                    max=25,
                    step=1,
                ),
                "number_of_queries": AgentActionConfig(
                    type="number",
                    label="Number of Queries",
                    description="The number of queries to use when retrieving context from the long term memory.",
                    value=3,
                    min=1,
                    max=10,
                    step=1,
                    condition=ai_assisted_condition,
                ),
                "answer_length": AgentActionConfig(
                    type="text",
                    label="Answer Length",
                    description="The maximum length of long term memory response.",
                    value="512",
                    choices=[
                        {"label": "Short (256)", "value": "256"},
                        {"label": "Medium (512)", "value": "512"},
                        {"label": "Long (1024)", "value": "1024"},
                    ],
                    condition=ai_assisted_condition,
                ),
                "cache": AgentActionConfig(
                    type="bool",
                    label="Cache RAG results",
                    description="Cache the long term memory for faster retrieval.",
                    note="This is a cross-agent cache, assuming they use the same options.",
                    value=True,
                ),
            },
        )

    # config property helpers

    @property
    def long_term_memory_enabled(self):
        return self.resolve_enabled("use_long_term_memory")

    @property
    def long_term_memory_retrieval_method(self):
        return self.resolve_config("use_long_term_memory", "retrieval_method")

    @property
    def long_term_memory_number_of_queries(self):
        return self.resolve_config("use_long_term_memory", "number_of_queries")

    @property
    def long_term_memory_answer_length(self):
        return int(self.resolve_config("use_long_term_memory", "answer_length"))

    @property
    def long_term_memory_cache(self):
        return self.resolve_config("use_long_term_memory", "cache")

    @property
    def long_term_memory_num_messages(self):
        return self.resolve_config("use_long_term_memory", "num_messages")

    @property
    def long_term_memory_cache_key(self):
        """
        Build the key from the various options
        """

        parts = [
            self.long_term_memory_retrieval_method,
            self.long_term_memory_number_of_queries,
            self.long_term_memory_answer_length,
            self.long_term_memory_num_messages,
        ]

        return "-".join(map(str, parts))

    def long_term_memory_cache_key_for(self, character: "Character | None") -> str:
        if character is None:
            return self.long_term_memory_cache_key
        # the viewer is part of the key: results built with the knowledge
        # filter on are not reused once it is off, and the other way round
        viewer = self.rag_knowledge_viewer(character)
        if viewer is None:
            return f"{self.long_term_memory_cache_key}-{character.name}-shared"
        if character_knowledge_enabled(self.scene):
            memory = instance.get_agent("memory")
            state = memory._audience_state(self.scene)
            topics = tuple(
                (key, tuple(topic.fact_ids))
                for key, topic in self.scene.world_state.topics.items()
            )
            settings = (
                memory.retrieval_recency_weight,
                memory.retrieval_mmr_threshold,
                memory.retrieval_entity_lookup,
                memory.retrieval_rerank,
                memory.max_distance,
                memory.topics_enabled,
                memory.topics_similarity_threshold,
                tuple(self.scene.active_characters),
                tuple(
                    (name, tuple(aliases))
                    for name, aliases in self.scene.world_state.character_name_mappings.items()
                ),
                self.scene.conversation_format,
                self.client.max_token_length,
                instance.get_agent("director").actor_direction_mode,
            )
            return hashlib.sha256(
                json.dumps(
                    (
                        self.long_term_memory_cache_key,
                        viewer,
                        state.collection_revision,
                        state.revision,
                        topics,
                        settings,
                    )
                ).encode()
            ).hexdigest()
        digest = knowledge_digest(self.scene)
        return f"{self.long_term_memory_cache_key}-{character.name}-{digest}"

    def connect(self, scene):
        super().connect(scene)

        # new scene, reset cache
        scene.rag_cache = {}

    # methods

    async def _rag_publish(
        self, content, character, *, key, scene, memory_revision, use_cache
    ):
        if (
            use_cache
            and self.scene is scene
            and key == self.long_term_memory_cache_key_for(character)
        ):
            await self.rag_set_cache(
                content, character, key=key, memory_revision=memory_revision
            )

    async def rag_set_cache(
        self,
        content: list[str],
        character: "Character | None" = None,
        *,
        key=None,
        memory_revision: int | None = None,
    ):
        if memory_revision is None:
            memory_revision = self.scene.memory_revision
        if memory_revision != self.scene.memory_revision:
            return
        self.scene.rag_cache[key or self.long_term_memory_cache_key_for(character)] = {
            "content": content,
            "memory_revision": memory_revision,
            "fingerprint": self.scene.history[-1].fingerprint
            if self.scene.history
            else 0,
        }

    async def rag_get_cache(
        self, character: "Character | None" = None
    ) -> list[str] | None:
        if not self.long_term_memory_cache:
            return None

        viewer = self.rag_knowledge_viewer(character)
        if viewer is not None and character_knowledge_enabled(self.scene):
            await instance.get_agent("memory").ensure_audience_index(self.scene)

        fingerprint = self.scene.history[-1].fingerprint if self.scene.history else 0
        cache = self.scene.rag_cache.get(self.long_term_memory_cache_key_for(character))

        if (
            cache
            and cache["fingerprint"] == fingerprint
            and cache["memory_revision"] == self.scene.memory_revision
        ):
            return cache["content"]

        return None

    async def rag_build(
        self,
        character: "Character | None" = None,
        sub_instruction: str = "",
        retrieval_method: str | None = None,
        include_raw_semantic: bool = True,
    ) -> list[str]:
        """Derive history internally; sub_instruction is an authored/director goal."""
        if not self.long_term_memory_enabled:
            return []

        async def retrieve(_collection=None):
            context = await self._rag_build(
                character=character,
                sub_instruction=sub_instruction,
                retrieval_method=retrieval_method,
                include_raw_semantic=include_raw_semantic,
            )
            return await self.rag_process_context(character, context)

        viewer = self.rag_knowledge_viewer(character)
        if viewer is not None and character_knowledge_enabled(self.scene):
            return await instance.get_agent("memory").audience_operation(
                viewer, retrieve
            )
        return await retrieve()

    async def rag_process_context(self, character, context):
        return context

    def rag_projected_history(
        self, viewer, *, budget=None, max_messages=None, keep_director=False
    ):
        """Use K04's projection options and hard token budget for retrieval."""
        return project_character_history(
            self.scene,
            viewer,
            budget=budget,
            max_messages=max_messages,
            keep_director=keep_director,
            direction_mode=instance.get_agent("director").actor_direction_mode,
        )

    async def rag_build_for_author(
        self,
        prompt: str = "",
        sub_instruction: str = "",
        retrieval_method: str | None = None,
        include_raw_semantic: bool = True,
        character: "Character | None" = None,
    ) -> list[str]:
        if character is not None and character_knowledge_enabled(self.scene):
            raise ValueError(
                "Perception characters must use rag_build without a raw prompt"
            )
        context = await self._rag_build(
            character=character,
            prompt=prompt,
            sub_instruction=sub_instruction,
            retrieval_method=retrieval_method,
            include_raw_semantic=include_raw_semantic,
        )
        return await self.rag_process_context(character, context)

    async def _rag_build(
        self,
        character: "Character | None" = None,
        prompt: str = "",
        sub_instruction: str = "",
        retrieval_method: str | None = None,
        include_raw_semantic: bool = True,
    ) -> list[str]:
        """
        Builds long term memory to be inserted into a prompt

        Arguments:

        - retrieval_method: Override the configured retrieval method.
          When provided, uses this method instead of the user's config.
        - include_raw_semantic: Whether to include raw semantic similarity
          results in the output. When False, only the AI-assisted results
          are returned (semantic results are still used as input context
          for the AI methods). Defaults to True.
        """

        if not self.long_term_memory_enabled:
            return []

        viewer = self.rag_knowledge_viewer(character)
        scoped = viewer is not None and character_knowledge_enabled(self.scene)
        # Cache only the configured, goal-free retrieval operation.
        use_cache = (
            self.long_term_memory_cache
            and retrieval_method is None
            and not prompt
            and not sub_instruction
            and include_raw_semantic
            # Legacy direct retrieval queries the store each time and needs no AI cache.
            and (scoped or self.long_term_memory_retrieval_method != "direct")
        )
        cache_key = self.long_term_memory_cache_key_for(character)
        cache_scene = self.scene
        memory_revision = cache_scene.memory_revision

        if use_cache:
            cached = await self.rag_get_cache(character)

            if cached:
                log.debug(
                    "Using cached long term memory",
                    agent=self.agent_type,
                    key=self.long_term_memory_cache_key_for(character),
                )
                return cached

        memory_context = ""
        memory_filter = self.rag_knowledge_filter(character)
        semantic_context = await self.semantic_context(
            num_messages=self.long_term_memory_num_messages,
            filter=memory_filter,
            **({"viewer": viewer} if scoped else {}),
        )

        if retrieval_method is None:
            retrieval_method = self.long_term_memory_retrieval_method

        if retrieval_method == "direct":
            # configuration is set to only use direct semantic matched context
            await self._rag_publish(
                semantic_context,
                character,
                key=cache_key,
                scene=cache_scene,
                memory_revision=memory_revision,
                use_cache=use_cache,
            )
            return semantic_context

        if not sub_instruction:
            if character:
                sub_instruction = f"continue the scene as {character.name}"
            elif hasattr(self, "rag_build_sub_instruction"):
                sub_instruction = await self.rag_build_sub_instruction()

        if not sub_instruction:
            sub_instruction = "continue the scene"

        world_state = instance.get_agent("world_state")

        if not prompt:
            prompt = (
                self.rag_projected_history(
                    viewer, budget=int(self.client.max_token_length * 0.75)
                )
                if scoped
                else self.scene.context_history(
                    keep_director=False,
                    budget=int(self.client.max_token_length * 0.75),
                    perspective=viewer,
                )
            )

        if isinstance(prompt, list):
            prompt = "\n".join(prompt)

        log.debug(
            "memory_rag_mixin.build_prompt_default_memory",
            direct=False,
            version=retrieval_method,
        )

        if retrieval_method == "questions":
            memory_context = (
                await world_state.analyze_text_and_extract_context(
                    prompt,
                    sub_instruction,
                    include_character_context=True,
                    response_length=self.long_term_memory_answer_length,
                    num_queries=self.long_term_memory_number_of_queries,
                    extra_context=semantic_context,
                    filter=memory_filter,
                    viewer=viewer,
                )
            ).split("\n")
        elif retrieval_method == "queries":
            memory_context = (
                await world_state.analyze_text_and_extract_context_via_queries(
                    prompt,
                    sub_instruction,
                    include_character_context=True,
                    response_length=self.long_term_memory_answer_length,
                    num_queries=self.long_term_memory_number_of_queries,
                    extra_context=semantic_context,
                    filter=memory_filter,
                    viewer=viewer,
                )
            )

        # keep the order (the entity lookup leads the semantic results)
        if include_raw_semantic:
            complete_context = list(dict.fromkeys(semantic_context + memory_context))
        else:
            complete_context = list(dict.fromkeys(memory_context))

        await self._rag_publish(
            complete_context,
            character,
            key=cache_key,
            scene=cache_scene,
            memory_revision=memory_revision,
            use_cache=use_cache,
        )

        return complete_context

    def rag_knowledge_viewer(self, character: "Character | None") -> str | None:
        """
        The character whose knowledge filters this agent's prompt, or None
        for the shared record. Agents with a switch override this.
        """
        return character.name if character is not None else None

    def rag_knowledge_filter(self, character: "Character | None"):
        viewer = self.rag_knowledge_viewer(character)
        if viewer is None or character_knowledge_enabled(self.scene):
            return None
        return KnowledgeIndex.from_scene(self.scene).retrieval_filter(
            self.scene, viewer
        )

    async def semantic_context(
        self,
        num_messages: int = 3,
        min_query_length: int = 100,
        max_response_tokens: int = 1024,
        filter: Callable | None = None,
        viewer: str | None = None,
    ):
        """Will retrieve context from the long term memory based on semantic similarity

        Args:
            num_messages (int, optional): The number of messages to consider (going back from the most recent message). Defaults to 3.
            min_query_length (int, optional): The minimum length of a query. Defaults to 100.
            max_response_tokens (int, optional): The maximum length of the response. Defaults to 1024.

        Returns:
            list[str]: The context retrieved from the long term memory
        """

        history = (
            list(
                reversed(
                    self.rag_projected_history(
                        viewer,
                        max_messages=num_messages,
                        keep_director=viewer,
                    )
                )
            )
            if viewer is not None
            else list(
                map(
                    str,
                    self.scene.collect_messages(
                        max_iterations=100,
                        max_messages=num_messages,
                        typ=["character", "narrator", "director"],
                    ),
                )
            )
        )
        log.debug(
            "memory_rag_mixin.build_prompt_default_memory",
            history=history,
            direct=True,
        )
        memory = instance.get_agent("memory")

        history_sentences = []
        for item in history:
            if not item.strip():
                continue
            sentences = compile_text_to_sentences(item)
            for sentence in sentences:
                if not sentence[1].strip():
                    continue
                history_sentences.append(sentence[1])

        history_sentences = compile_sentences_to_length(
            history_sentences, min_query_length
        )

        queries = [i for i in history + history_sentences if i.strip()]

        for query in queries:
            log.debug("memory_rag_mixin.build_prompt_default_memory", query=query)

        entity_context = await self.entity_lookup(
            history, filter=filter, **({"viewer": viewer} if viewer is not None else {})
        )

        context = await memory.multi_query(
            queries,
            max_tokens=max_response_tokens,
            iterate=5,
            filter=filter,
            over_fetch=3 if filter is not None else 1,
            topic_first=True,
            **({"viewer": viewer} if viewer is not None else {}),
        )

        if not entity_context:
            return context
        return entity_context + [item for item in context if item not in entity_context]

    async def entity_lookup(
        self, history: list[str], filter: Callable | None = None, *, viewer=None
    ) -> list:
        """
        Descriptions of characters the recent lines name who are not in the
        scene, fetched by metadata (no similarity search).
        """
        memory = instance.get_agent("memory")
        if not memory.retrieval_entity_lookup:
            return []

        text = "\n".join(history)
        if not text.strip():
            return []

        scene = self.scene
        named = [
            name
            for name in scene.inactive_characters
            if any(_alias_named(alias, text) for alias in _entity_aliases(scene, name))
        ]
        if not named:
            return []

        found = []
        for name in named:
            documents = await memory.get_documents_by_meta(
                {"character": name, "typ": "base_attribute", "attr": "description"},
                **({"viewer": viewer} if viewer is not None else {}),
            )
            # `<name>.description`, then the paragraphs `.description.<n>` in
            # number order (text order would put .10 before .2)
            for doc_id in sorted(
                documents,
                key=lambda identity: _paragraph_order(
                    documents[identity].meta.get("knowledge_id", identity)
                ),
            ):
                doc = documents[doc_id]
                if filter is not None and not filter(doc):
                    continue
                found.append(doc)

        log.debug("entity lookup", named=named, documents=len(found))
        return found
